# CREATE PORTFOLIO SUMMARY
# ============================================================

def create_portfolio_summary(
    history
):

    if history.empty:

        return {

            "starting_capital":
                INITIAL_CAPITAL,

            "realized_pnl":
                0.0,

            "unrealized_pnl":
                0.0,

            "net_pnl":
                0.0,

            "portfolio_value":
                INITIAL_CAPITAL,

            "open_positions":
                0,

            "closed_trades":
                0,

            "wins":
                0,

            "losses":
                0,
        }

    status_series = (
        history["Status"]
        .astype(str)
        .str.upper()
    )

    closed = history[
        status_series == "CLOSED"
    ].copy()

    open_positions = history[
        status_series == "OPEN"
    ].copy()

    # --------------------------------------------------------
    # Realized PnL
    # --------------------------------------------------------

    realized_pnl = 0.0

    if not closed.empty:

        realized_pnl = (
            pd.to_numeric(
                closed["Net PnL"],
                errors="coerce"
            )
            .fillna(0)
            .sum()
        )

    # --------------------------------------------------------
    # Unrealized PnL
    # --------------------------------------------------------

    unrealized_pnl = 0.0

    if not open_positions.empty:

        unrealized_pnl = (
            pd.to_numeric(
                open_positions["Net PnL"],
                errors="coerce"
            )
            .fillna(0)
            .sum()
        )

    # --------------------------------------------------------
    # Total PnL
    # --------------------------------------------------------

    net_pnl = (
        realized_pnl
        +
        unrealized_pnl
    )

    # --------------------------------------------------------
    # Wins / losses
    # --------------------------------------------------------

    wins = 0
    losses = 0

    if not closed.empty:

        net_values = pd.to_numeric(
            closed["Net PnL"],
            errors="coerce"
        ).fillna(0)

        wins = int(
            (net_values > 0).sum()
        )

        losses = int(
            (net_values < 0).sum()
        )

    # --------------------------------------------------------
    # Portfolio value
    # --------------------------------------------------------

    portfolio_value = (
        INITIAL_CAPITAL
        +
        net_pnl
    )

    return {

        "starting_capital":
            INITIAL_CAPITAL,

        "realized_pnl":
            float(realized_pnl),

        "unrealized_pnl":
            float(unrealized_pnl),

        "net_pnl":
            float(net_pnl),

        "portfolio_value":
            float(portfolio_value),

        "open_positions":
            len(open_positions),

        "closed_trades":
            len(closed),

        "wins":
            wins,

        "losses":
            losses,
    }


