def load_trade_history():

    if not os.path.exists(
        TRADE_HISTORY_FILE
    ):

        return pd.DataFrame()

    try:

        df = pd.read_csv(
            TRADE_HISTORY_FILE
        )

        if df.empty:

            return pd.DataFrame()

        # ----------------------------------------------------
        # Convert dates
        # ----------------------------------------------------

        date_columns = [
            "Signal Date",
            "Entry Date",
            "Exit Date",
        ]

        for column in date_columns:

            if column in df.columns:

                df[column] = pd.to_datetime(
                    df[column],
                    errors="coerce"
                )

        # ----------------------------------------------------
        # Normalize numeric columns
        # ----------------------------------------------------

        numeric_columns = [
            "Entry Price",
            "Stop Loss",
            "Take Profit",
            "Shares",
            "Exit Price",
            "Latest Price",
            "Gross PnL",
            "Transaction Costs",
            "Net PnL",
            "Return %",
            "Bars Held",
        ]

        for column in numeric_columns:

            if column in df.columns:

                df[column] = pd.to_numeric(
                    df[column],
                    errors="coerce"
                )

        return df

    except Exception as error:

        print(
            f"⚠️ Could not read trade history: "
            f"{error}"
        )

        return pd.DataFrame()


# ============================================================
# SAVE TRADE HISTORY
# ============================================================

def save_trade_history(
    df
):

    if df is None or df.empty:

        return

    output = df.copy()

    # --------------------------------------------------------
    # Format dates
    # --------------------------------------------------------

    date_columns = [
        "Signal Date",
        "Entry Date",
        "Exit Date",
    ]

    for column in date_columns:

        if column in output.columns:

            dates = pd.to_datetime(
                output[column],
                errors="coerce"
            )

            output[column] = dates.dt.strftime(
                "%Y-%m-%d"
            )

    output.to_csv(
        TRADE_HISTORY_FILE,
        index=False
    )


# ============================================================
# BUILD SIGNAL ID
# ============================================================

def build_signal_id(
    symbol,
    signal_date,
    signal
):

    date_text = pd.Timestamp(
        signal_date
    ).strftime("%Y-%m-%d")

    return (
        f"{symbol}|"
        f"{date_text}|"
        f"{signal}"
    )


# ============================================================
# CHECK DUPLICATE SIGNAL
# ============================================================

def signal_already_processed(
    signal_id,
    history
):

    if history.empty:

        return False

    if "Signal ID" not in history.columns:

        return False

    return (
        history["Signal ID"]
        .astype(str)
        .eq(signal_id)
        .any()
    )


