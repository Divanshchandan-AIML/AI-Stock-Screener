# LOAD PAPER SIGNALS
# ============================================================

def load_paper_signals():

    if not os.path.exists(SIGNALS_FILE):

        print()
        print(
            "⚠️ No paper signal file found."
        )

        print(
            f"   Expected: {SIGNALS_FILE}"
        )

        print(
            "   Stage 10 may simply have generated "
            "no new crossover."
        )

        return pd.DataFrame()

    try:

        df = pd.read_csv(
            SIGNALS_FILE
        )

    except Exception as error:

        print(
            f"⚠️ Could not read paper signals: "
            f"{error}"
        )

        return pd.DataFrame()

    if df.empty:

        print(
            "⚠️ paper_signals.csv is empty."
        )

        return pd.DataFrame()

    required_columns = [
        "Symbol",
        "Signal Date",
        "Signal",
        "Entry Price",
        "Stop Loss",
        "Take Profit",
        "Shares",
    ]

    missing = [
        column
        for column in required_columns
        if column not in df.columns
    ]

    if missing:

        print(
            "❌ Missing columns in "
            "paper_signals.csv:"
        )

        for column in missing:

            print(
                f"   - {column}"
            )

        return pd.DataFrame()

    # --------------------------------------------------------
    # Normalize date
    # --------------------------------------------------------

    df["Signal Date"] = pd.to_datetime(
        df["Signal Date"],
        errors="coerce"
    )

    # --------------------------------------------------------
    # Normalize numeric columns
    # --------------------------------------------------------

    numeric_columns = [
        "Entry Price",
        "Stop Loss",
        "Take Profit",
        "Shares",
    ]

    for column in numeric_columns:

        df[column] = pd.to_numeric(
            df[column],
            errors="coerce"
        )

    # --------------------------------------------------------
    # Remove invalid records
    # --------------------------------------------------------

    df = df.dropna(
        subset=[
            "Symbol",
            "Signal Date",
            "Signal",
            "Entry Price",
            "Stop Loss",
            "Take Profit",
            "Shares",
        ]
    )

    # --------------------------------------------------------
    # Normalize signal
    # --------------------------------------------------------

    df["Signal"] = (
        df["Signal"]
        .astype(str)
        .str.upper()
        .str.strip()
    )

    # --------------------------------------------------------
    # Keep only BUY / SELL
    # --------------------------------------------------------

    df = df[
        df["Signal"].isin(
            ["BUY", "SELL"]
        )
    ]

    # --------------------------------------------------------
    # Sort
    # --------------------------------------------------------

    df = (
        df
        .sort_values("Signal Date")
        .reset_index(drop=True)
    )

    return df


